using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Pine.Infrastructure.Ai.Extraction.LayoutLm;

/// <summary>
/// RoBERTa byte-level BPE, read from a Hugging Face <c>tokenizer.json</c>, reproducing the ids the
/// <c>tokenizers</c> library gives for one already-split word with <c>add_prefix_space=true</c>.
/// </summary>
/// <remarks>
/// <para>
/// WHY NOT <c>Microsoft.ML.Tokenizers</c>. Exact id parity with the training run is the whole
/// requirement: one different id changes the logits. This class is small, has nothing to
/// configure, and is checked against ids generated by the reference library (parity fixtures in the
/// unit tests), which is a stronger statement than "the BCL type is probably the same".
/// </para>
/// <para>No network; the instance is immutable after loading except for a thread-safe cache.</para>
/// </remarks>
public sealed partial class LayoutLmTokenizer
{
    /// <summary>The id of <c>&lt;s&gt;</c>.</summary>
    public const int BosId = 0;

    /// <summary>The id of <c>&lt;/s&gt;</c>.</summary>
    public const int EosId = 2;

    private const int UnkId = 3;
    private const int MaxCachedWords = 20_000;

    // GPT-2 / RoBERTa pre-tokenisation pattern (what ByteLevel use_regex=true applies).
    [GeneratedRegex(@"'s|'t|'re|'ve|'m|'ll|'d| ?\p{L}+| ?\p{N}+| ?[^\s\p{L}\p{N}]+|\s+(?!\S)|\s+")]
    private static partial Regex PreTokenRegex();

    private static readonly char[] ByteToChar = BuildByteToChar();

    private readonly Dictionary<string, int> _vocab;
    private readonly Dictionary<(string, string), int> _ranks;
    private readonly Dictionary<string, int> _added;
    private readonly System.Collections.Concurrent.ConcurrentDictionary<string, int[]> _cache = new();

    private LayoutLmTokenizer(Dictionary<string, int> vocab, Dictionary<(string, string), int> ranks, Dictionary<string, int> added)
    {
        _vocab = vocab;
        _ranks = ranks;
        _added = added;
    }

    /// <summary>Loads vocabulary, merges and special tokens from a <c>tokenizer.json</c> file.</summary>
    public static LayoutLmTokenizer Load(string tokenizerJsonPath)
    {
        using var stream = File.OpenRead(tokenizerJsonPath);
        using var doc = JsonDocument.Parse(stream);
        var model = doc.RootElement.GetProperty("model");

        var vocab = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var entry in model.GetProperty("vocab").EnumerateObject())
        {
            vocab[entry.Name] = entry.Value.GetInt32();
        }

        var ranks = new Dictionary<(string, string), int>();
        var rank = 0;
        foreach (var merge in model.GetProperty("merges").EnumerateArray())
        {
            string left, right;
            if (merge.ValueKind == JsonValueKind.String)
            {
                var parts = merge.GetString()!.Split(' ');
                (left, right) = (parts[0], parts[1]);
            }
            else
            {
                (left, right) = (merge[0].GetString()!, merge[1].GetString()!);
            }

            ranks.TryAdd((left, right), rank++);
        }

        var added = new Dictionary<string, int>(StringComparer.Ordinal);
        if (doc.RootElement.TryGetProperty("added_tokens", out var addedTokens))
        {
            foreach (var token in addedTokens.EnumerateArray())
            {
                added[token.GetProperty("content").GetString()!] = token.GetProperty("id").GetInt32();
            }
        }

        return new LayoutLmTokenizer(vocab, ranks, added);
    }

    /// <summary>Token ids for one word, without special tokens.</summary>
    public int[] EncodeWord(string word)
    {
        ArgumentNullException.ThrowIfNull(word);
        if (word.Length == 0)
        {
            return [];
        }

        if (_cache.TryGetValue(word, out var cached))
        {
            return cached;
        }

        var ids = new List<int>();
        var position = 0;
        foreach (var (start, length, id) in FindAddedTokens(word))
        {
            if (start > position)
            {
                EncodeSegment(word[position..start], ids);
            }

            ids.Add(id);
            position = start + length;
        }

        if (position < word.Length)
        {
            EncodeSegment(word[position..], ids);
        }

        var result = ids.ToArray();
        if (_cache.Count < MaxCachedWords)
        {
            _cache[word] = result;
        }

        return result;
    }

    private List<(int Start, int Length, int Id)> FindAddedTokens(string text)
    {
        // Special tokens are matched in the raw input before pre-tokenisation, as the reference does.
        var found = new List<(int, int, int)>();
        if (text.IndexOf('<', StringComparison.Ordinal) < 0)
        {
            return found;
        }

        var index = 0;
        while (index < text.Length)
        {
            var best = (Start: -1, Length: 0, Id: 0);
            foreach (var (content, id) in _added)
            {
                var at = text.IndexOf(content, index, StringComparison.Ordinal);
                if (at >= 0 && (best.Start < 0 || at < best.Start || (at == best.Start && content.Length > best.Length)))
                {
                    best = (at, content.Length, id);
                }
            }

            if (best.Start < 0)
            {
                break;
            }

            found.Add(best);
            index = best.Start + best.Length;
        }

        return found;
    }

    private void EncodeSegment(string segment, List<int> output)
    {
        // add_prefix_space: every pre-tokenised word is encoded as if preceded by a space.
        if (segment.Length == 0)
        {
            return;
        }

        if (segment[0] != ' ')
        {
            segment = " " + segment;
        }

        foreach (Match match in PreTokenRegex().Matches(segment))
        {
            var mapped = new StringBuilder();
            foreach (var b in Encoding.UTF8.GetBytes(match.Value))
            {
                mapped.Append(ByteToChar[b]);
            }

            foreach (var piece in Bpe(mapped.ToString()))
            {
                output.Add(_vocab.TryGetValue(piece, out var id) ? id : UnkId);
            }
        }
    }

    private List<string> Bpe(string token)
    {
        // The mapped alphabet is BMP code points, so one char is one initial symbol.
        var symbols = token.Select(c => c.ToString()).ToList();

        while (symbols.Count > 1)
        {
            var bestRank = int.MaxValue;
            var bestIndex = -1;
            for (var i = 0; i < symbols.Count - 1; i++)
            {
                if (_ranks.TryGetValue((symbols[i], symbols[i + 1]), out var r) && r < bestRank)
                {
                    bestRank = r;
                    bestIndex = i;
                }
            }

            if (bestIndex < 0)
            {
                break;
            }

            var (a, b) = (symbols[bestIndex], symbols[bestIndex + 1]);
            var merged = new List<string>(symbols.Count);
            var j = 0;
            while (j < symbols.Count)
            {
                if (j < symbols.Count - 1 && symbols[j] == a && symbols[j + 1] == b)
                {
                    merged.Add(a + b);
                    j += 2;
                }
                else
                {
                    merged.Add(symbols[j]);
                    j++;
                }
            }

            symbols = merged;
        }

        return symbols;
    }

    /// <summary>GPT-2's reversible byte to printable-unicode table.</summary>
    private static char[] BuildByteToChar()
    {
        var printable = new List<int>();
        printable.AddRange(Enumerable.Range('!', '~' - '!' + 1));
        printable.AddRange(Enumerable.Range(0xA1, 0xAC - 0xA1 + 1));
        printable.AddRange(Enumerable.Range(0xAE, 0xFF - 0xAE + 1));

        var table = new char[256];
        var assigned = new bool[256];
        foreach (var b in printable)
        {
            table[b] = (char)b;
            assigned[b] = true;
        }

        var n = 0;
        for (var b = 0; b < 256; b++)
        {
            if (!assigned[b])
            {
                table[b] = (char)(256 + n);
                n++;
            }
        }

        return table;
    }
}
