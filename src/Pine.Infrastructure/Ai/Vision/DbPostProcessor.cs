using System;
using System.Collections.Generic;
using System.Linq;

namespace Pine.Infrastructure.Ai.Vision;

/// <summary>A point in map or image pixel coordinates.</summary>
internal readonly record struct Point2(double X, double Y);

/// <summary>A detected text box: four corners (top-left, top-right, bottom-right, bottom-left) and its score.</summary>
internal sealed record DetectedBox(Point2[] Quad, float Score);

/// <summary>
/// Turns a DB (differentiable binarisation) probability map into text boxes. A line-by-line port of
/// <c>det_postprocess</c> in <c>research/scripts/onnx_ocr_reference.py</c> (docs/65 section 4).
/// </summary>
/// <remarks>
/// <para>
/// PURE MANAGED CODE: no ONNX runtime, no image library, no OpenCV. Arrays in, boxes out, so it is
/// unit-tested against golden fixtures generated by the Python reference
/// (<c>research/scripts/gen_onnx_ocr_csharp_fixtures.py</c>) and runs unchanged on every head.
/// </para>
/// <para>
/// Replaces what PaddleOCR gets from OpenCV and Clipper: <c>findContours</c> becomes 8-connected
/// components, <c>minAreaRect</c> becomes a convex hull plus rotating calipers (exact), and the Clipper
/// "unclip" of a rectangle becomes the closed form: grow each side by <c>area * ratio / perimeter</c>.
/// </para>
/// <para>
/// TUNED-CONSTANTS BOUNDARY (TD-118): the thresholds below describe the exported PP-OCRv5 detector and
/// match Sdcb.PaddleOCR's defaults (binarisation 0.3, box score 0.7, unclip 1.5, minimum side 3, at most
/// 1000 candidates, 10 px row tolerance). They are literals, not options.
/// </para>
/// </remarks>
internal static class DbPostProcessor
{
    internal const float DefaultThreshold = 0.3f;
    internal const float DefaultBoxThreshold = 0.7f;
    internal const double DefaultUnclipRatio = 1.5;
    private const double MinSize = 3;
    private const int MaxCandidates = 1000;
    private const double RowTolerance = 10;

    /// <summary>Extracts the text boxes from a probability map.</summary>
    /// <param name="prob">Row-major probabilities, <paramref name="mapHeight"/> x <paramref name="mapWidth"/>.</param>
    /// <param name="mapWidth">Width of the map in pixels.</param>
    /// <param name="mapHeight">Height of the map in pixels.</param>
    /// <param name="origWidth">Width of the original image; the boxes are scaled to it.</param>
    /// <param name="origHeight">Height of the original image.</param>
    /// <param name="threshold">Binarisation threshold on the probability.</param>
    /// <param name="boxThreshold">Minimum mean probability inside a box.</param>
    /// <param name="unclipRatio">Expansion ratio of the box.</param>
    /// <returns>The boxes in reading order, in original-image pixel coordinates.</returns>
    internal static IReadOnlyList<DetectedBox> Process(
        ReadOnlySpan<float> prob,
        int mapWidth,
        int mapHeight,
        int origWidth,
        int origHeight,
        float threshold = DefaultThreshold,
        float boxThreshold = DefaultBoxThreshold,
        double unclipRatio = DefaultUnclipRatio)
    {
        if (prob.Length != mapWidth * mapHeight)
        {
            throw new ArgumentException("The probability map does not match its stated size.", nameof(prob));
        }

        var boxes = new List<Point2[]>();
        var scores = new List<float>();

        foreach (var comp in ConnectedComponents(prob, mapWidth, mapHeight, threshold))
        {
            var (corners, rectW, rectH) = MinAreaRect(comp);
            if (Math.Min(rectW, rectH) < MinSize)
            {
                continue;
            }

            var quad = OrderBox(corners);
            var x0 = Math.Max(0, Math.Min((int)Math.Floor(quad.Min(p => p.X)), mapWidth - 1));
            var x1 = Math.Max(0, Math.Min((int)Math.Ceiling(quad.Max(p => p.X)), mapWidth - 1));
            var y0 = Math.Max(0, Math.Min((int)Math.Floor(quad.Min(p => p.Y)), mapHeight - 1));
            var y1 = Math.Max(0, Math.Min((int)Math.Ceiling(quad.Max(p => p.Y)), mapHeight - 1));

            if (!TryQuadScore(prob, mapWidth, quad, x0, y0, x1, y1, out var score) || score < boxThreshold)
            {
                continue;
            }

            // Closed-form unclip of a rectangle (round joins): grow every side by d.
            var area = rectW * rectH;
            var perimeter = 2 * (rectW + rectH);
            var d = area * unclipRatio / perimeter;
            var cx = (corners[0].X + corners[1].X + corners[2].X + corners[3].X) / 4;
            var cy = (corners[0].Y + corners[1].Y + corners[2].Y + corners[3].Y) / 4;
            var (ax, ay) = Normalised(corners[1].X - corners[0].X, corners[1].Y - corners[0].Y);
            var (bx, by) = Normalised(corners[3].X - corners[0].X, corners[3].Y - corners[0].Y);
            var hw = (rectW / 2) + d;
            var hh = (rectH / 2) + d;

            if (Math.Min(2 * hw, 2 * hh) < MinSize + 2)
            {
                continue;
            }

            var big = new[]
            {
                new Point2(cx - (ax * hw) - (bx * hh), cy - (ay * hw) - (by * hh)),
                new Point2(cx + (ax * hw) - (bx * hh), cy + (ay * hw) - (by * hh)),
                new Point2(cx + (ax * hw) + (bx * hh), cy + (ay * hw) + (by * hh)),
                new Point2(cx - (ax * hw) + (bx * hh), cy - (ay * hw) + (by * hh)),
            };
            var qb = OrderBox(big);
            var sx = (double)origWidth / mapWidth;
            var sy = (double)origHeight / mapHeight;
            for (var i = 0; i < 4; i++)
            {
                qb[i] = new Point2(
                    Math.Clamp(Math.Round(qb[i].X * sx), 0, origWidth),
                    Math.Clamp(Math.Round(qb[i].Y * sy), 0, origHeight));
            }

            boxes.Add(qb);
            scores.Add(score);
        }

        // PaddleOCR sorted_boxes: top to bottom, then left to right inside a 10 px row. OrderBy is stable.
        var order = Enumerable.Range(0, boxes.Count)
            .OrderBy(i => boxes[i][0].Y)
            .ThenBy(i => boxes[i][0].X)
            .ToArray();
        for (var i = 0; i < order.Length - 1; i++)
        {
            for (var j = i; j >= 0; j--)
            {
                var a = boxes[order[j]];
                var b = boxes[order[j + 1]];
                if (Math.Abs(b[0].Y - a[0].Y) < RowTolerance && b[0].X < a[0].X)
                {
                    (order[j], order[j + 1]) = (order[j + 1], order[j]);
                }
                else
                {
                    break;
                }
            }
        }

        return order.Select(i => new DetectedBox(boxes[i], scores[i])).ToList();
    }

    private static (double X, double Y) Normalised(double x, double y)
    {
        var n = Math.Sqrt((x * x) + (y * y));
        if (n == 0)
        {
            n = 1;
        }

        return (x / n, y / n);
    }

    /// <summary>
    /// 8-connected components of <c>prob &gt; threshold</c> as pixel coordinates, in scan order of their
    /// first pixel. Only the first <see cref="MaxCandidates"/> are returned, like the reference.
    /// </summary>
    private static List<List<Point2>> ConnectedComponents(ReadOnlySpan<float> prob, int w, int h, float threshold)
    {
        var result = new List<List<Point2>>();
        var seen = new bool[w * h];
        var stack = new Stack<int>();

        for (var start = 0; start < prob.Length && result.Count < MaxCandidates; start++)
        {
            if (!(prob[start] > threshold) || seen[start])
            {
                continue;
            }

            var comp = new List<Point2>();
            stack.Push(start);
            seen[start] = true;
            while (stack.Count > 0)
            {
                var idx = stack.Pop();
                var y = idx / w;
                var x = idx - (y * w);
                comp.Add(new Point2(x, y));
                for (var dy = -1; dy <= 1; dy++)
                {
                    var yy = y + dy;
                    if (yy < 0 || yy >= h)
                    {
                        continue;
                    }

                    for (var dx = -1; dx <= 1; dx++)
                    {
                        var xx = x + dx;
                        if (xx < 0 || xx >= w)
                        {
                            continue;
                        }

                        var n = (yy * w) + xx;
                        if (prob[n] > threshold && !seen[n])
                        {
                            seen[n] = true;
                            stack.Push(n);
                        }
                    }
                }
            }

            result.Add(comp);
        }

        return result;
    }

    /// <summary>Convex hull (monotone chain; collinear points dropped).</summary>
    internal static Point2[] ConvexHull(IReadOnlyCollection<Point2> points)
    {
        var p = points.Distinct().OrderBy(q => q.X).ThenBy(q => q.Y).ToList();
        if (p.Count <= 2)
        {
            return p.ToArray();
        }

        static double Cross(Point2 o, Point2 a, Point2 b) => ((a.X - o.X) * (b.Y - o.Y)) - ((a.Y - o.Y) * (b.X - o.X));

        var lo = new List<Point2>();
        foreach (var q in p)
        {
            while (lo.Count >= 2 && Cross(lo[^2], lo[^1], q) <= 0)
            {
                lo.RemoveAt(lo.Count - 1);
            }

            lo.Add(q);
        }

        var up = new List<Point2>();
        for (var i = p.Count - 1; i >= 0; i--)
        {
            var q = p[i];
            while (up.Count >= 2 && Cross(up[^2], up[^1], q) <= 0)
            {
                up.RemoveAt(up.Count - 1);
            }

            up.Add(q);
        }

        lo.RemoveAt(lo.Count - 1);
        up.RemoveAt(up.Count - 1);
        lo.AddRange(up);
        return lo.ToArray();
    }

    /// <summary>Exact minimum-area bounding rectangle of a point set: corners and the extents along its two axes.</summary>
    internal static (Point2[] Corners, double A, double B) MinAreaRect(IReadOnlyCollection<Point2> pts)
    {
        var hull = ConvexHull(pts);
        if (hull.Length == 1)
        {
            return (new[] { hull[0], hull[0], hull[0], hull[0] }, 0, 0);
        }

        var found = false;
        double bestArea = 0, bux = 0, buy = 0, bvx = 0, bvy = 0, ba0 = 0, ba1 = 0, bb0 = 0, bb1 = 0;
        var n = hull.Length;
        for (var i = 0; i < n; i++)
        {
            var ex = hull[(i + 1) % n].X - hull[i].X;
            var ey = hull[(i + 1) % n].Y - hull[i].Y;
            var ln = Math.Sqrt((ex * ex) + (ey * ey));
            if (ln == 0)
            {
                continue;
            }

            var ux = ex / ln;
            var uy = ey / ln;
            var vx = -uy;
            var vy = ux;
            double aMin = double.MaxValue, aMax = double.MinValue, bMin = double.MaxValue, bMax = double.MinValue;
            foreach (var q in hull)
            {
                var a = (q.X * ux) + (q.Y * uy);
                var b = (q.X * vx) + (q.Y * vy);
                aMin = Math.Min(aMin, a);
                aMax = Math.Max(aMax, a);
                bMin = Math.Min(bMin, b);
                bMax = Math.Max(bMax, b);
            }

            var area = (aMax - aMin) * (bMax - bMin);
            if (!found || area < bestArea)
            {
                found = true;
                (bestArea, bux, buy, bvx, bvy, ba0, ba1, bb0, bb1) = (area, ux, uy, vx, vy, aMin, aMax, bMin, bMax);
            }
        }

        Point2 At(double a, double b) => new((a * bux) + (b * bvx), (a * buy) + (b * bvy));
        return (new[] { At(ba0, bb0), At(ba1, bb0), At(ba1, bb1), At(ba0, bb1) }, ba1 - ba0, bb1 - bb0);
    }

    /// <summary>Orders four corners top-left, top-right, bottom-right, bottom-left, as PaddleOCR's <c>get_mini_boxes</c>.</summary>
    internal static Point2[] OrderBox(Point2[] corners)
    {
        var p = corners.OrderBy(q => q.X).ToArray(); // stable, like Python's sorted()
        var (i1, i4) = p[1].Y > p[0].Y ? (0, 1) : (1, 0);
        var (i2, i3) = p[3].Y > p[2].Y ? (2, 3) : (3, 2);
        return new[] { p[i1], p[i2], p[i3], p[i4] };
    }

    /// <summary>Mean probability over the pixels of the window whose centre lies in the convex quad.</summary>
    private static bool TryQuadScore(ReadOnlySpan<float> prob, int mapWidth, Point2[] quad, int x0, int y0, int x1, int y1, out float score)
    {
        var cross = ((quad[1].X - quad[0].X) * (quad[2].Y - quad[1].Y)) - ((quad[1].Y - quad[0].Y) * (quad[2].X - quad[1].X));
        var sign = cross >= 0 ? 1.0 : -1.0;
        var sum = 0.0;
        var count = 0;
        for (var y = y0; y <= y1; y++)
        {
            for (var x = x0; x <= x1; x++)
            {
                var inside = true;
                for (var i = 0; i < 4 && inside; i++)
                {
                    var a = quad[i];
                    var b = quad[(i + 1) % 4];
                    var cr = ((b.X - a.X) * (y - a.Y)) - ((b.Y - a.Y) * (x - a.X));
                    var len = Math.Sqrt(((b.X - a.X) * (b.X - a.X)) + ((b.Y - a.Y) * (b.Y - a.Y)));
                    inside = (cr * sign) >= -0.5 * len; // half-pixel tolerance ~ fillPoly boundary
                }

                if (inside)
                {
                    sum += prob[(y * mapWidth) + x];
                    count++;
                }
            }
        }

        score = count == 0 ? 0 : (float)(sum / count);
        return count > 0;
    }
}
